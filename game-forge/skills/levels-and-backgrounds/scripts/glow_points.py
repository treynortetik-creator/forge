#!/usr/bin/env python3
"""glow_points.py: bake hand-placed light points (candle flames, torches, windows) of a painted backdrop into a data file, with
1:1 crops to read them off and an overlay to verify them.

Why hand-placed: automatic detection was tried twice on a 2560x1440 painted plate and rejected. Luminance blobs pick skulls and ribs
(painted paper tops out near L=221, candle wax near 215), and snapping hand seeds to the nearest bright blob drifted 10-30 px onto
neighbours. What worked: read each flame centre (just above the wax) off a 1:1 crop, then verify with an overlay. Re-run only when
the backdrop image changes. Pure Pillow. Needs: pip install pillow.

  python3 glow_points.py crops  plate.png crops_dir [--size 640]        # 1:1 tiles with coordinate ticks (every 50 px, labels every 100)
  python3 glow_points.py bake   plate.png points.json out.ts|out.json [--overlay overlay.png] [--min-dist 12]
points.json is [[x, y], ...] in plate pixels. bake dedupes points closer than --min-dist, sorts them, and writes either a TypeScript module
(GENERATED header, PLATE size + the list) or plain JSON, chosen by the output extension. In the engine, draw one additive warm blob per
point, scaled with the plate, with a gentle two-sine flicker (alpha = resting strength, flicker = +- a fraction of it).
"""
import json, os, sys
from PIL import Image, ImageDraw


def crops(src, outdir, size=640):
    im = Image.open(src).convert('RGB')
    os.makedirs(outdir, exist_ok=True)
    n = 0
    for y0 in range(0, im.height, size):
        for x0 in range(0, im.width, size):
            t = im.crop((x0, y0, min(x0 + size, im.width), min(y0 + size, im.height)))
            d = ImageDraw.Draw(t)
            for gx in range((x0 + 49) // 50 * 50, x0 + t.width, 50):
                major = gx % 100 == 0
                d.line([(gx - x0, 0), (gx - x0, 12 if major else 6)], fill=(255, 255, 0))
                if major:
                    d.text((gx - x0 + 2, 12), str(gx), fill=(255, 255, 0))
            for gy in range((y0 + 49) // 50 * 50, y0 + t.height, 50):
                major = gy % 100 == 0
                d.line([(0, gy - y0), (12 if major else 6, gy - y0)], fill=(0, 255, 255))
                if major:
                    d.text((14, gy - y0 - 5), str(gy), fill=(0, 255, 255))
            t.save(os.path.join(outdir, f'crop_{x0}_{y0}.png'))
            n += 1
    print(n, 'crops ->', outdir, f'(plate {im.width}x{im.height}; tick labels are plate pixels)')


def bake(src, pts_file, out, overlay=None, min_dist=12):
    im = Image.open(src).convert('RGB')
    raw = [tuple(p) for p in json.load(open(pts_file))]
    pts = []
    for p in raw:
        if all((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 > min_dist ** 2 for q in pts):
            pts.append(p)
    pts.sort()
    if out.endswith('.json'):
        json.dump({'plate': {'w': im.width, 'h': im.height}, 'points': [list(p) for p in pts]}, open(out, 'w'))
    else:
        with open(out, 'w') as f:
            f.write(f'// GENERATED by glow_points.py: light-point centres in plate pixels ({im.width}x{im.height}). Do not hand-edit.\n')
            f.write(f'export const PLATE = {{ w: {im.width}, h: {im.height} }};\nexport const GLOW: ReadonlyArray<readonly [number, number]> = [\n')
            for p in pts:
                f.write(f'  [{p[0]}, {p[1]}],\n')
            f.write('];\n')
    print(len(pts), 'points (', len(raw) - len(pts), 'deduped ) ->', out)
    if overlay:
        d = ImageDraw.Draw(im)
        for x, y in pts:
            d.ellipse([x - 6, y - 6, x + 6, y + 6], outline=(255, 0, 0), width=3)
        im.save(overlay)
        print('overlay ->', overlay)


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] in ('-h', '--help'):
        print(__doc__); sys.exit(0)
    a = sys.argv[1:]
    if len(a) >= 3 and a[0] == 'crops':
        crops(a[1], a[2], int(a[a.index('--size') + 1]) if '--size' in a else 640)
    elif len(a) >= 4 and a[0] == 'bake':
        bake(a[1], a[2], a[3], a[a.index('--overlay') + 1] if '--overlay' in a else None, int(a[a.index('--min-dist') + 1]) if '--min-dist' in a else 12)
    else:
        print(__doc__)
        sys.exit(2)
